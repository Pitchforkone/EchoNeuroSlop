/// <summary>
/// Интерфейс интерактивного объекта.
/// Реализуйте этот интерфейс, чтобы объект мог реагировать на нажатие клавиши взаимодействия (E).
/// Зарегистрируйте слушателя в InteractZone, чтобы получать уведомления о взаимодействии.
/// </summary>
public interface IInteractable
{
    /// <summary>
    /// Вызывается при взаимодействии игрока с объектом (нажатие E).
    /// </summary>
    void OnInteract();
}
